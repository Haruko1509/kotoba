const sandbox = {};
vm.createContext(sandbox);
const code = fs.readFileSync('web-preview/js/chapters-data.js', 'utf8').replace('const novelChaptersData =', 'var novelChaptersData =');
vm.runInContext(code, sandbox);

const chapsData = sandbox.novelChaptersData;

Object.keys(specializedTitles).forEach(novelId => {
  if (chapsData[novelId]) {
    specializedTitles[novelId].forEach((st, idx) => {
      if (chapsData[novelId][idx]) {
        chapsData[novelId][idx].title = `第${idx+1}章：${st}`;
        chapsData[novelId][idx].titleJp = st;
      }
    });
  }
});

const out = `// ===================================================================
// KOTOBA ODYSSEY - 25-CHAPTER CANONICAL DATA REGISTRY (ALL 105 NOVELS)
// ===================================================================

const novelChaptersData = ${JSON.stringify(chapsData, null, 2)};

function getNovelChapters(novelId) {
  if (novelChaptersData[novelId]) {
    return novelChaptersData[novelId];
  }
  const fallback = [];
  for (let i = 1; i <= 25; i++) {
    fallback.push({
      chapterNumber: i,
      title: \`第\${i}章：物語の展開 (\${i}/25)\`,
      titleJp: \`第\${i}章\`,
      titleVn: \`Chương \${i}\`,
      content: '日本語の文章がここに表示されます。'
    });
  }
  return fallback;
}
`;

fs.writeFileSync('web-preview/js/chapters-data.js', out, 'utf8');
console.log('✓ Successfully enriched specialized chapter titles for major novels in chapters-data.js!');
